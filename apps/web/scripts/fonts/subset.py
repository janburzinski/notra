import hashlib
import json
import os
import re
import subprocess
import sys
import unicodedata
from pathlib import Path

from fontTools import __version__, subset
from fontTools.ttLib import TTFont, sfnt


WEB = Path(__file__).resolve().parents[2]
ROOT = WEB.parents[1]
HERE = Path(__file__).resolve().parent
OUTPUT = WEB / "src/fonts/subsets"
FEATURES = ["ccmp", "locl", "rlig", "liga", "clig", "calt", "kern", "mark", "mkmk", "tnum"]


def ranges(points):
    groups = []
    for point in sorted(points):
        if groups and point == groups[-1][-1] + 1:
            groups[-1].append(point)
        else:
            groups.append([point])
    return ",".join(f"U+{g[0]:X}" + (f"-{g[-1]:X}" if len(g) > 1 else "") for g in groups)


def inspect(path):
    font = TTFont(path)
    return {
        "bytes": path.stat().st_size,
        "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
        "glyphs": len(font.getGlyphOrder()),
        "characters": len(font.getBestCmap()),
        "unicodeRange": ranges(font.getBestCmap()),
        "axes": {a.axisTag: [a.minValue, a.defaultValue, a.maxValue] for a in font["fvar"].axes} if "fvar" in font else {},
        "features": {tag: sorted({r.FeatureTag for r in font[tag].table.FeatureList.FeatureRecord}) for tag in ("GSUB", "GPOS") if tag in font},
        "hintTables": [tag for tag in ("fpgm", "prep", "cvt ", "gasp") if tag in font],
        "hintedGlyphs": sum(bool(getattr(font["glyf"][name], "program", None) and font["glyf"][name].program.getBytecode()) for name in font.getGlyphOrder()) if "glyf" in font else 0,
    }


def css_points(css):
    points = set()
    for match in re.finditer(r"U\+([0-9A-F]+)(?:-([0-9A-F]+))?", css, re.I):
        points.update(range(int(match[1], 16), int(match[2] or match[1], 16) + 1))
    return points


def main():
    assert __version__ == "4.60.1", "Install scripts/fonts/requirements.txt first."
    OUTPUT.mkdir(parents=True, exist_ok=True)
    paths = sorted(p for p in (WEB / "src").rglob("*") if p.suffix in {".tsx", ".ts", ".css", ".mdx", ".md", ".json"} and "fonts" not in p.parts and p.name not in {"routeTree.gen.ts", "fonts.css"})
    ui_sources = WEB / "src/styles/ui-sources.css"
    paths += [ui_sources.parent / source for source in re.findall(r'@source "([^"]+)"', ui_sources.read_text())]
    for path in paths:
        if path.suffix != ".css":
            continue
        for relative in re.findall(r'@import "([^"]+)"', path.read_text()):
            if relative.startswith("."):
                imported = (path.parent / relative).resolve()
                if imported.is_file() and imported.name != "fonts.css" and imported not in paths:
                    paths.append(imported)
    text = "".join(p.read_text() for p in paths)
    wanted = {ord(c) for c in text} | set(range(0x20, 0x180)) | {0xAD, 0x2010, 0x2122}
    wanted -= set(range(0x2E80, 0xA000)) | set(range(0xAC00, 0xD7B0)) | set(range(0xF900, 0xFB00))
    wanted.update(ord(c) for point in list(wanted) for c in unicodedata.normalize("NFD", chr(point)))
    report = {"corpusSha256": hashlib.sha256(text.encode()).hexdigest(), "corpusFiles": len(paths), "before": {}, "after": {}, "legacyBefore": {}, "legacyAfter": {}, "otherAssets": {}}
    css = ["/* Generated by scripts/fonts/subset.py; run manually, never during builds. */"]
    configs = [
        ("inter", "Inter Variable", "Notra Text", "@fontsource-variable/inter", "index.css", "300 700"),
        ("instrument", "Instrument Serif", "Notra Accent", "@fontsource/instrument-serif", "400.css", "400"),
    ]
    for stem, family, internal, package, stylesheet, weight in configs:
        package_dir = WEB / "node_modules" / package
        assert json.loads((package_dir / "package.json").read_text())["version"] == "5.3.0", "Fontsource changed: refresh matching sources and repeat pixel comparisons first."
        original_css = (package_dir / stylesheet).read_text()
        faces = []
        for face in re.findall(r"@font-face\s*\{([^}]+)\}", original_css):
            file = re.search(r"url\(\./([^)]*\.woff2)\)", face)[1]
            path = package_dir / file
            report["before"][path.name] = inspect(path)
            if stem == "instrument":
                report["legacyBefore"][path.with_suffix(".woff").name] = inspect(path.with_suffix(".woff"))
            coverage = set(TTFont(path).getBestCmap()) & css_points(face)
            report["before"][path.name]["cssUnicodeRange"] = ranges(coverage)
            if "-latin-ext-" in path.name:
                part = "extended"
            elif "-latin-" in path.name:
                part = "core"
            else:
                part = path.name.removeprefix("inter-").split("-wght-")[0] + "-extended"
            features = set().union(*(set(tags) for tags in report["before"][path.name]["features"].values()))
            faces.append((part, path, coverage, features))
        for part, source, coverage, features in faces:
            if not wanted & coverage:
                continue
            output = OUTPUT / f"{stem}-{part}.woff2"
            current = subset.load_font(source, subset.Options(recalc_timestamp=False))
            current.cfg["fontTools.ttLib.tables.otBase:USE_HARFBUZZ_REPACKER"] = False
            original_cmap = set(current.getBestCmap())
            points = wanted & original_cmap
            options = subset.Options()
            options.layout_features = [feature for feature in FEATURES if feature in features]
            options.hinting = False
            options.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14, 16, 17, 25]
            options.name_legacy = True
            options.name_languages = [0x409]
            options.recalc_timestamp = False
            worker = subset.Subsetter(options=options)
            worker.populate(unicodes=points)
            worker.subset(current)
            names = {1: internal, 3: f"{internal}-{part}-1", 4: internal, 6: internal.replace(" ", ""), 16: internal, 25: internal.replace(" ", "")}
            for record in current["name"].names:
                if record.nameID in names:
                    record.string = names[record.nameID].encode(record.getEncoding())
            current.flavor = "woff2"
            current.save(output)
            generated = TTFont(output)
            actual = set(generated.getBestCmap())
            assert points <= actual <= original_cmap, (output, actual ^ points)
            assert not any(tag in generated for tag in ("fpgm", "prep", "cvt "))
            assert generated["name"].getDebugName(1) == internal
            assert generated["name"].getDebugName(6) == internal.replace(" ", "")
            assert all(a.axisTag == "wght" for a in generated["fvar"].axes) if "fvar" in generated else stem == "instrument"
            report["after"][output.name] = inspect(output)
            declared = actual & coverage
            assert declared
            report["after"][output.name]["cssUnicodeRange"] = ranges(declared)
            format_hint = "woff2-variations" if stem == "inter" else "woff2"
            src = f'url("../fonts/subsets/{output.name}?no-inline") format("{format_hint}")'
            if stem == "instrument":
                sfnt.USE_ZOPFLI = True
                current.flavor = "woff"
                current.save(output.with_suffix(".woff"))
                report["legacyAfter"][output.with_suffix(".woff").name] = inspect(output.with_suffix(".woff"))
                src += f', url("../fonts/subsets/{output.with_suffix(".woff").name}?no-inline") format("woff")'
            css += ["@font-face {", f'  font-family: "{family}";', "  font-style: normal;", "  font-display: swap;", f"  font-weight: {weight};", f"  src: {src};", f"  unicode-range: {ranges(declared)};", "}"]
    satoshi = WEB / "src/fonts/Satoshi-Variable.woff2"
    report["before"][satoshi.name] = inspect(satoshi)
    report["after"][satoshi.name] = inspect(satoshi)
    for path in sorted((WEB / "public/fonts").glob("*.woff2")):
        report["otherAssets"][str(path.relative_to(WEB))] = inspect(path)
    for weight in (400, 500, 600):
        path = WEB / f"node_modules/@fontsource/inter/files/inter-latin-{weight}-normal.woff"
        report["otherAssets"][f"og/{path.name}"] = inspect(path)
    (WEB / "src/styles/fonts.css").write_text("\n".join(css) + "\n")
    (HERE / "inventory.json").write_text(json.dumps(report, indent=2) + "\n")
    subprocess.run([ROOT / "node_modules/.bin/oxfmt", WEB / "src/styles/fonts.css", HERE / "inventory.json"], check=True, cwd=ROOT)
    print(json.dumps({group: {name: info["bytes"] for name, info in report[group].items()} for group in ("before", "after")}, indent=2))


if __name__ == "__main__":
    if os.environ.get("PYTHONHASHSEED") != "0":
        os.execve(sys.executable, [sys.executable, *sys.argv], {**os.environ, "PYTHONHASHSEED": "0"})
    main()
