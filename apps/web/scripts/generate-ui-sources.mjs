import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const webRoot = fileURLToPath(new URL("../", import.meta.url));
const uiRoot = path.resolve(webRoot, "../../packages/ui/src");
// The `ui` workspace (apps/ui): `ui/*` imports point into its registry, whose
// files import `@/components/ui/*`, aliased to @notra/ui like in vite.config.ts.
const registryApp = path.resolve(webRoot, "../ui");
const registryRoot = path.join(registryApp, "registry");
const registryExports = JSON.parse(
  readFileSync(path.join(registryApp, "package.json"), "utf8")
).exports;
const output = path.join(webRoot, "src/styles/ui-sources.css");
const extensions = [".ts", ".tsx", ".js", ".jsx", ".mjs", ".mdx"];
const pending = [];
const visited = new Set();
const sources = new Set();

const transpilers = {
  ".js": new Bun.Transpiler({ loader: "js" }),
  ".jsx": new Bun.Transpiler({ loader: "jsx" }),
  ".mjs": new Bun.Transpiler({ loader: "js" }),
  ".ts": new Bun.Transpiler({ loader: "ts" }),
  ".tsx": new Bun.Transpiler({ loader: "tsx" }),
};
const MDX_IMPORT =
  /^(?:import\s*["'][^"'\n]+["']|(?:import|export)\b(?:[^\n]|\n(?!\s*\n))*?\bfrom\s*["'][^"'\n]+["']);?/gm;

const STATIC_IMPORT =
  /^\s*(?:import|export)\b[^;]*?\bfrom\s*["']([^"']+)["']/gm;

function importSpecifiers(filename) {
  const code = readFileSync(filename, "utf8");
  if (path.extname(filename) === ".mdx") {
    return (code.match(MDX_IMPORT) ?? []).flatMap((statement) =>
      transpilers[".js"].scanImports(statement).map((entry) => entry.path)
    );
  }
  const staticImports = [...code.matchAll(STATIC_IMPORT)].map(
    (match) => match[1]
  );
  return [
    ...transpilers[path.extname(filename)]
      .scanImports(code)
      .map((entry) => entry.path),
    ...staticImports,
  ];
}

function registryExport(specifier) {
  const key = `./${specifier.slice("ui/".length)}`;
  for (const [pattern, target] of Object.entries(registryExports)) {
    const [prefix, suffix = ""] = pattern.split("*");
    if (pattern === key) {
      return path.join(registryApp, target);
    }
    if (
      pattern.includes("*") &&
      key.startsWith(prefix) &&
      key.endsWith(suffix) &&
      key.length >= prefix.length + suffix.length
    ) {
      const match = key.slice(prefix.length, key.length - suffix.length);
      return path.join(registryApp, target.replace("*", match));
    }
  }
  return undefined;
}

const isShared = (filename) =>
  filename.startsWith(`${uiRoot}${path.sep}`) ||
  filename.startsWith(`${registryRoot}${path.sep}`);

function collect(directory) {
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const filename = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      collect(filename);
    } else if (extensions.includes(path.extname(filename))) {
      pending.push(filename);
    }
  }
}

function resolveSource(base) {
  return [
    ...(extensions.includes(path.extname(base)) ? [base] : []),
    ...extensions.map((extension) => `${base}${extension}`),
    ...extensions.map((extension) => path.join(base, `index${extension}`)),
  ].find((candidate) => existsSync(candidate));
}

collect(path.join(webRoot, "src"));
for (const filename of ["source.config.ts"]) {
  const entry = path.join(webRoot, filename);
  if (existsSync(entry)) {
    pending.push(entry);
  }
}

while (pending.length > 0) {
  const filename = pending.pop();
  if (visited.has(filename)) {
    continue;
  }
  visited.add(filename);
  if (isShared(filename)) {
    sources.add(filename);
  }
  for (const specifier of importSpecifiers(filename)) {
    let base;
    if (specifier.startsWith("@notra/ui/")) {
      base = path.join(uiRoot, specifier.slice("@notra/ui/".length));
    } else if (specifier.startsWith("ui/")) {
      base = registryExport(specifier);
      if (!base) {
        throw new Error(`Unknown ui export: ${specifier} in ${filename}`);
      }
    } else if (
      specifier.startsWith("@/components/ui/") &&
      filename.startsWith(`${registryRoot}${path.sep}`)
    ) {
      base = path.join(uiRoot, specifier.slice("@/".length));
    } else if (specifier.startsWith(".")) {
      base = path.resolve(path.dirname(filename), specifier);
    } else {
      continue;
    }
    if (path.extname(base) === ".css") {
      continue;
    }
    const resolved = resolveSource(base);
    if (resolved) {
      pending.push(resolved);
    } else if (
      specifier.startsWith("@notra/ui/") ||
      specifier.startsWith("ui/") ||
      isShared(filename)
    ) {
      throw new Error(
        `Cannot resolve shared UI source: ${specifier} in ${filename}`
      );
    }
  }
}

const css = [
  "/* Generated by scripts/generate-ui-sources.mjs. Do not edit by hand. */",
  ...[...sources]
    .sort()
    .map(
      (filename) =>
        `@source "${path.relative(path.dirname(output), filename).split(path.sep).join("/")}";`
    ),
  "",
].join("\n");
if (process.argv.includes("--check")) {
  if (!existsSync(output) || readFileSync(output, "utf8") !== css) {
    throw new Error(
      "Shared UI sources are stale. Run bun run styles:generate in apps/web."
    );
  }
} else if (!existsSync(output) || readFileSync(output, "utf8") !== css) {
  writeFileSync(output, css);
}
console.log(`Tailwind: ${sources.size} reachable shared UI source files.`);
