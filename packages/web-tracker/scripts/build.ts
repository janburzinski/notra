import { createHash } from "node:crypto";
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import { brotliCompressSync, gzipSync } from "node:zlib";

import {
  DOCS_CSP_HASH_PATTERN,
  DOCS_PINNED_BUILD_PATTERN,
  TRACKER_RELEASE_FILE_PATTERN,
  TRACKER_VERSION_LENGTH,
} from "../src/constants/script";
import { trackerReleaseFile } from "../src/utils/release";

const root = new URL("..", import.meta.url).pathname;
export const RELEASES_DIR = `${root}releases/`;
/** The install docs, whose example tags show the current pinned builds. */
export const DOCS_FILE = `${root}../../apps/docs/analytics/install/script-tag.mdx`;

/** notra.js, or with `plus` the superset notra.plus.js that adds errors. */
export async function buildTracker(plus = false): Promise<string> {
  const result = await Bun.build({
    entrypoints: [`${root}src/tracker.ts`],
    target: "browser",
    // The source is already an IIFE; "esm" avoids a second wrapper.
    format: "esm",
    minify: true,
    define: { NOTRA_PLUS: String(plus) },
  });
  if (!result.success) {
    throw new AggregateError(result.logs, "Tracker build failed");
  }
  const [output] = result.outputs;
  if (!output) {
    throw new Error("Tracker build produced no output");
  }
  return (await output.text()).trim();
}

/** Content-addressed, so an archived file's name proves its bytes. */
export function trackerVersion(script: string): string {
  return createHash("sha256")
    .update(script)
    .digest("hex")
    .slice(0, TRACKER_VERSION_LENGTH);
}

/** The `integrity` attribute browsers check the served bytes against. */
export function trackerIntegrity(script: string): string {
  return `sha384-${createHash("sha384").update(script).digest("base64")}`;
}

export function renderModule(script: string, plusScript: string): string {
  return [
    "// Generated by `bun run build` in packages/web-tracker. Do not edit.",
    `export const TRACKER_SCRIPT_VERSION = "${trackerVersion(script)}";`,
    `export const TRACKER_SCRIPT_INTEGRITY = "${trackerIntegrity(script)}";`,
    `export const TRACKER_SCRIPT = ${JSON.stringify(script)};`,
    `export const TRACKER_PLUS_SCRIPT_VERSION = "${trackerVersion(plusScript)}";`,
    `export const TRACKER_PLUS_SCRIPT_INTEGRITY = "${trackerIntegrity(plusScript)}";`,
    `export const TRACKER_PLUS_SCRIPT = ${JSON.stringify(plusScript)};`,
    "",
  ].join("\n");
}

/**
 * The docs with every pinned tag pointing at the current builds, so a tag
 * copied from the docs carries the real file name and integrity, not a
 * placeholder.
 */
export function renderDocs(
  docs: string,
  script: string,
  plusScript: string
): string {
  const current = {
    file: trackerReleaseFile(trackerVersion(script), false),
    integrity: trackerIntegrity(script),
  };
  const plus = {
    file: trackerReleaseFile(trackerVersion(plusScript), true),
    integrity: trackerIntegrity(plusScript),
  };
  return docs
    .replaceAll(
      DOCS_PINNED_BUILD_PATTERN,
      (_match, isPlus?: string, beforeIntegrity?: string) => {
        const release = isPlus ? plus : current;
        return beforeIntegrity === undefined
          ? release.file
          : `${release.file}${beforeIntegrity}${release.integrity}`;
      }
    )
    .replaceAll(DOCS_CSP_HASH_PATTERN, `'${current.integrity}'`);
}

/** Every archived build, by file name, in a stable order. */
export function readReleases(): Map<string, string> {
  const files = readdirSync(RELEASES_DIR)
    .filter((file) => TRACKER_RELEASE_FILE_PATTERN.test(file))
    .toSorted();
  return new Map(
    files.map((file) => [file, readFileSync(`${RELEASES_DIR}${file}`, "utf8")])
  );
}

export function renderReleases(releases: ReadonlyMap<string, string>): string {
  const entries = [...releases].map(
    ([file, script]) =>
      `  ${JSON.stringify(file)}: {\n    integrity: "${trackerIntegrity(script)}",\n    script: ${JSON.stringify(script)},\n  },`
  );
  return [
    "// Generated by `bun run build` in packages/web-tracker. Do not edit.",
    'import type { TrackerRelease } from "../types/release";',
    "",
    "/** Every released build, so pinned script tags keep loading. */",
    "export const TRACKER_RELEASES: Readonly<Record<string, TrackerRelease>> = {",
    ...entries,
    "};",
    "",
  ].join("\n");
}

/**
 * Archives a build under its content address. An existing file is never
 * rewritten: pages pin its integrity, so changed bytes would break them.
 */
export function archiveRelease(script: string, plus: boolean): string {
  const file = trackerReleaseFile(trackerVersion(script), plus);
  const path = `${RELEASES_DIR}${file}`;
  if (existsSync(path)) {
    if (readFileSync(path, "utf8") !== script) {
      throw new Error(`Archived ${file} differs from its build`);
    }
  } else {
    mkdirSync(RELEASES_DIR, { recursive: true });
    writeFileSync(path, script);
  }
  return file;
}

function describe(name: string, script: string): string {
  const bytes = Buffer.from(script);
  return `${name}: ${bytes.length} B raw, ${gzipSync(bytes, { level: 9 }).length} B gzip, ${brotliCompressSync(bytes).length} B brotli`;
}

if (import.meta.main) {
  const [script, plusScript] = await Promise.all([
    buildTracker(),
    buildTracker(true),
  ]);
  archiveRelease(script, false);
  archiveRelease(plusScript, true);
  await Bun.write(`${root}dist/notra.js`, script);
  await Bun.write(`${root}dist/notra.plus.js`, plusScript);
  await Bun.write(
    `${root}src/generated/script.ts`,
    renderModule(script, plusScript)
  );
  await Bun.write(
    `${root}src/generated/releases.ts`,
    renderReleases(readReleases())
  );
  // Docker images leave out apps/docs; there is nothing to update then.
  if (existsSync(DOCS_FILE)) {
    await Bun.write(
      DOCS_FILE,
      renderDocs(readFileSync(DOCS_FILE, "utf8"), script, plusScript)
    );
  }
  console.log(describe("notra.js", script));
  console.log(describe("notra.plus.js", plusScript));
}
